const A = "A".charCodeAt(0);
const a = "a".charCodeAt(0);

/** Mathematical alphanumeric letters, minus the ones Unicode had already placed in Letterlike Symbols. */
function letters(
  command: string,
  pkg: string,
  name: string,
  upper: number,
  lower: number | undefined,
  holes: Record<string, string>,
): LatexSymbol[] {
  const out: LatexSymbol[] = [];
  for (let i = 0; i < 26; i++) {
    const L = String.fromCharCode(A + i);
    out.push({
      command: `\\${command}{${L}}`,
      char: holes[L] ?? String.fromCodePoint(upper + i),
      package: pkg,
      category: "letters",
      names: [`${name} ${L}`, `${name} capital ${L.toLowerCase()}`],
    });
  }
  if (lower !== undefined) {
    for (let i = 0; i < 26; i++) {
      const l = String.fromCharCode(a + i);
      out.push({
        command: `\\${command}{${l}}`,
        char: holes[l] ?? String.fromCodePoint(lower + i),
        package: pkg,
        category: "letters",
        names: [`${name} ${l}`, `${name} small ${l}`],
      });
    }
  }
  return out;
}

