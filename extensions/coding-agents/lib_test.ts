Deno.test("reading lines: across chunks, CRLF-free, no trailing newline", async () => {
  const dir = await Deno.makeTempDir();
  try {
    const long = "y".repeat(200_000);
    await Deno.writeTextFile(`${dir}/a.jsonl`, `one\n${long}\n\nlast`);
    const lines: string[] = [];
    for await (const l of readLines(`${dir}/a.jsonl`)) lines.push(l);
    assertEquals(lines.length, 4);
    assertEquals(lines[1].length, 200_000);
    assertEquals(lines[3], "last");
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

