Deno.test("manifest: terminals and Aider folders are allowed", async () => {
  const { parse } = await import("@std/toml");
  const manifest = parse(await Deno.readTextFile(new URL("./backslash.toml", import.meta.url))) as {
    permissions: { read: string[]; run: string[] };
    preferences: { name: string; default?: string }[];
  };
  assertEquals(manifest.permissions.run, TERMINALS);
  const readable = new Set(manifest.permissions.read);
  for (const f of parseFolders(manifest.preferences.find((p) => p.name === "folders")!.default, "~")) {
    assert(readable.has(f), `${f} is not readable`);
  }
  assert(readable.has("~/.claude/projects") && readable.has("~/.codex/sessions"));
});
