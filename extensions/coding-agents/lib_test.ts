Deno.test("Claude Code: prompts, replies, context, title and last answer", () => {
  const r = new ClaudeReader("/home/me/.claude/projects/-home-me-Projects-web-app/x.jsonl", "x");
  for (const line of CLAUDE) r.add(line);
  const s = r.finish();
  assertEquals(s.id, "6f1c0e2a-1111-4222-8333-944455556666");
  assertEquals(s.cwd, "/home/me/Projects/web-app");
  assertEquals(s.branch, "fix/login");
  assertEquals(s.version, "2.1.3");
  assertEquals(s.prompts, [
    "Fix the login bug: users are sent back to /login after signing in",
    "/review auth.ts",
    "Now add a test",
  ]);
  assertEquals(s.promptCount, 3);
  assertEquals(s.replyCount, 3);
  assertEquals(s.lastReply, "Added auth.test.ts; all 12 tests pass.");
  assertEquals(s.model, "claude-opus-4-5");
  assertEquals(s.summary, "Fixing the OAuth login redirect");
  assertEquals(s.title, "Login redirect fix");
  assertEquals(s.started, Date.parse("2026-10-20T09:00:00.500Z"));
  assertEquals(s.updated, Date.parse("2026-10-20T09:05:00.000Z"));
  assertEquals(sessionTitle(s), "Login redirect fix");
  assertEquals(
    sessionTitle({ ...s, title: undefined }),
    "Fix the login bug: users are sent back to /login after signing in",
  );
});

