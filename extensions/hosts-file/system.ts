// Reading /etc/hosts, and writing it as root through pkexec with a backup.

import {
  BACKUP_PATH,
  checkBeforeWrite,
  HOSTS_PATH,
  type HostsFile,
  parseHosts,
  pkexecError,
  RESTORE_SCRIPT,
  serialize,
  WRITE_SCRIPT,
} from "./lib.ts";

const changes = new EventTarget();

/** Yields what `load` gives, then again after each change, until the view closes. */
export async function* live<T>(load: () => Promise<T>, signal: AbortSignal): AsyncGenerator<T> {
  while (!signal.aborted) {
    yield await load();
    await new Promise<void>((resolve) => {
      const done = () => {
        changes.removeEventListener("change", done);
        signal.removeEventListener("abort", done);
        resolve();
      };
      changes.addEventListener("change", done);
      signal.addEventListener("abort", done);
    });
  }
}

export interface Loaded {
  text: string;
  file: HostsFile;
}

export async function read(): Promise<Loaded> {
  let text: string;
  try {
    text = await Deno.readTextFile(HOSTS_PATH);
  } catch (e) {
    if (e instanceof Deno.errors.NotFound) return { text: "", file: parseHosts("") };
    throw new Error(`${HOSTS_PATH} can't be read: ${(e as Error).message}`);
  }
  return { text, file: parseHosts(text) };
}

export async function hasBackup(): Promise<boolean> {
  try {
    return (await Deno.stat(BACKUP_PATH)).isFile;
  } catch {
    return false;
  }
}

/** /etc/hosts generated by the system: NixOS links it to its store. */
async function managedBy(): Promise<string | undefined> {
  try {
    const info = await Deno.lstat(HOSTS_PATH);
    if (!info.isSymlink) return undefined;
    const target = await Deno.readLink(HOSTS_PATH);
    if (/\/etc\/static\/|\/nix\/store\//.test(target)) {
      return "NixOS manages /etc/hosts: add entries with networking.hosts or networking.extraHosts in your configuration";
    }
    return undefined;
  } catch {
    return undefined;
  }
}

async function asRoot(script: string, stdin?: string): Promise<void> {
  let child: Deno.ChildProcess;
  try {
    child = new Deno.Command("pkexec", {
      args: ["/bin/sh", "-c", script],
      stdin: stdin === undefined ? "null" : "piped",
      stdout: "piped",
      stderr: "piped",
      // Two minutes to type the password.
      signal: AbortSignal.timeout(120_000),
    }).spawn();
  } catch (e) {
    if (e instanceof Deno.errors.NotFound) throw new Error("pkexec (polkit) is needed to change the hosts file");
    throw e;
  }
  if (stdin !== undefined) {
    const w = child.stdin.getWriter();
    await w.write(new TextEncoder().encode(stdin));
    await w.close();
  }
  const { code, stderr } = await child.output();
  const err = new TextDecoder().decode(stderr).trim();
  const denied = pkexecError(code, err);
  if (denied) throw new Error(denied);
  if (code !== 0) throw new Error(err.split("\n").filter(Boolean).pop() || `Writing the hosts file failed (${code})`);
}

/**
 * Writes the new file over /etc/hosts, after checking it, that nobody changed the file
 * meanwhile, and keeping the previous one as /etc/hosts.backslash.bak.
 */
export async function write(before: string, file: HostsFile): Promise<void> {
  const after = serialize(file);
  if (after === before) return;
  const managed = await managedBy();
  if (managed) throw new Error(managed);
  const problem = checkBeforeWrite(before, after);
  if (problem) throw new Error(problem);
  const now = await Deno.readTextFile(HOSTS_PATH).catch(() => "");
  if (now !== before) throw new Error("The hosts file changed since it was opened: look at it again");
  await asRoot(WRITE_SCRIPT, after);
  changes.dispatchEvent(new Event("change"));
  const written = await Deno.readTextFile(HOSTS_PATH).catch(() => "");
  if (written !== after) {
    throw new Error(`The hosts file doesn't read back as written: the previous one is in ${BACKUP_PATH}`);
  }
}

/** Brings back the file as it was before the last change. */
export async function restoreBackup(): Promise<void> {
  const backup = await Deno.readTextFile(BACKUP_PATH);
  if (!backup.trim()) throw new Error("The backup is empty: nothing was restored");
  const managed = await managedBy();
  if (managed) throw new Error(managed);
  await asRoot(RESTORE_SCRIPT);
  changes.dispatchEvent(new Event("change"));
}
