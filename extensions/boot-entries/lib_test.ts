Deno.test("quoted GRUB titles", () => {
  assertEquals(readQuoted(`'Ubuntu' --class os {`), ["Ubuntu", " --class os {"]);
  assertEquals(readQuoted(`'Joe'\\''s entry' {`), ["Joe's entry", " {"]);
  assertEquals(readQuoted(`"a \\"b\\"" x`), [`a "b"`, " x"]);
  assertEquals(readQuoted(`plain rest`), ["plain", " rest"]);
});

Deno.test("grub.cfg menu entries and submenus", () => {
  const menu = parseGrubCfg(GRUB_CFG);
  assertEquals(menu.entries.map((e) => e.title), [
    "Ubuntu",
    "Ubuntu, with Linux 6.8.0-47-generic",
    "Ubuntu, with Linux 6.8.0-47-generic (recovery mode)",
    "Windows Boot Manager (on /dev/nvme0n1p1)",
    "UEFI Firmware Settings",
    `Joe's "test" entry`,
  ]);
  assertEquals(menu.entries[0].target, "gnulinux-simple-5c0e8a7d");
  assertEquals(
    menu.entries[1].target,
    "gnulinux-advanced-5c0e8a7d>gnulinux-6.8.0-47-generic-advanced-5c0e8a7d",
  );
  assertEquals(menu.entries[1].submenu, "Advanced options for Ubuntu");
  assertEquals(menu.entries[1].version, "6.8.0-47-generic");
  assertEquals(menu.entries[2].os, "linux");
  assertEquals(menu.entries[3].os, "windows");
  assertEquals(menu.entries[3].submenu, undefined);
  assertEquals(menu.entries[4].os, "firmware");
  assertEquals(menu.entries[5].target, `Joe's "test" entry`);
  // The header sets `${next_entry}` first, then the real default.
  assertEquals(menu.defaultRef, "0");
  assertEquals(menu.supportsNextEntry, true);
  assertEquals(menu.usesBls, false);
});

Deno.test("grubenv and default/next entries", () => {
  const env = parseGrubenv(
    "# GRUB Environment Block\n# WARNING: Do not edit this file by tools other than grub-editenv!!!\nsaved_entry=osprober-efi-0A1B-2C3D\nnext_entry=Advanced options for Ubuntu>Ubuntu, with Linux 6.8.0-47-generic\n####",
  );
  assertEquals(env.saved_entry, "osprober-efi-0A1B-2C3D");
  const menu = parseGrubCfg(GRUB_CFG);
  const marked = markGrub(menu, env);
  assertEquals(marked[0].isDefault, true);
  assertEquals(marked[1].isNext, true);
  assertEquals(marked.filter((e) => e.isNext).length, 1);

  const saved = markGrub({ ...menu, defaultRef: "${saved_entry}" }, env);
  assertEquals(saved.find((e) => e.isDefault)?.os, "windows");
  // Index 1 is the submenu: 2 is Windows.
  const indexed = markGrub({ ...menu, defaultRef: "2" }, {});
  assertEquals(indexed.find((e) => e.isDefault)?.title, "Windows Boot Manager (on /dev/nvme0n1p1)");
});

Deno.test("GRUB references by id, title or index", () => {
  const [simple, advanced] = parseGrubCfg(GRUB_CFG).entries;
  assert(grubMatches(simple, "0"));
  assert(!grubMatches(advanced, "1"));
  assert(grubMatches(simple, "Ubuntu"));
  assert(grubMatches(advanced, "gnulinux-advanced-5c0e8a7d>Ubuntu, with Linux 6.8.0-47-generic"));
  assert(!grubMatches(advanced, "Ubuntu"));
  assert(!grubMatches(simple, ""));
});

Deno.test("Fedora: blscfg entries, newest kernel first", () => {
  const cfg = parseGrubCfg(
    `set default="\${saved_entry}"\nif [ x"\${next_entry}" != x ]; then\n  true\nfi\ninsmod blscfg\nblscfg\n`,
  );
  assertEquals(cfg.usesBls, true);
  assertEquals(cfg.defaultRef, "${saved_entry}");
  const older = parseBlsEntry(
    "4f1c-6.10.12-200.fc40.x86_64",
    "title Fedora Linux (6.10.12-200.fc40.x86_64) 40 (Workstation Edition)\nversion 6.10.12-200.fc40.x86_64\nlinux /vmlinuz-6.10.12-200.fc40.x86_64\noptions root=UUID=… ro rhgb quiet\n",
  );
  const newer = parseBlsEntry(
    "4f1c-6.11.4-201.fc40.x86_64",
    "title Fedora Linux (6.11.4-201.fc40.x86_64) 40 (Workstation Edition)\nversion 6.11.4-201.fc40.x86_64\nlinux /vmlinuz-6.11.4-201.fc40.x86_64\n",
  );
  assertEquals(older.os, "linux");
  assertEquals(older.options, "root=UUID=… ro rhgb quiet");
  assertEquals(sortBls([older, newer]).map((e) => e.target), [newer.target, older.target]);
  assert(compareVersions("6.11.4", "6.10.12") > 0);
  assert(compareVersions("6.9", "6.10") < 0);
  assertEquals(compareVersions("1.0", "1.0"), 0);
});

