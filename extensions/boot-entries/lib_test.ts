const EFI_17 = [
  "BootCurrent: 0002",
  "Timeout: 0 seconds",
  "BootOrder: 0002,0000",
  "Boot0000* Windows Boot Manager",
  "Boot0002* ubuntu",
  "Boot0004* UEFI OS HD(1,GPT,0a,0x800,0x82000)/File(\\EFI\\BOOT\\BOOTX64.EFI)..BO",
].join("\n");

Deno.test("efibootmgr 18", () => {
  const m = parseEfibootmgr(EFI_18);
  assertEquals(m.current, "0001");
  assertEquals(m.next, "0000");
  assertEquals(m.timeout, 1);
  assertEquals(m.order, ["0001", "0000", "0003", "0002"]);
  assertEquals(m.entries.map((e) => e.target), ["0001", "0000", "0003", "0002"]);
  const [linux, windows, usb, pxe] = m.entries;
  assertEquals(linux.title, "Linux Boot Manager");
  assertEquals(linux.isCurrent, true);
  assertEquals(linux.isDefault, true);
  assertEquals(windows.os, "windows");
  assertEquals(windows.isNext, true);
  assertEquals(efiFile(windows.path), "\\EFI\\Microsoft\\Boot\\bootmgfw.efi57494e444f5753000100");
  assertEquals(usb.os, "removable");
  assertEquals(pxe.os, "network");
  assertEquals(pxe.active, false);
});

Deno.test("efibootmgr 17", () => {
  const m = parseEfibootmgr(EFI_17);
  assertEquals(m.next, undefined);
  assertEquals(m.entries.map((e) => e.title), ["ubuntu", "Windows Boot Manager", "UEFI OS"]);
  assertEquals(m.entries[0].os, "linux");
  assertEquals(m.entries[2].path, "HD(1,GPT,0a,0x800,0x82000)/File(\\EFI\\BOOT\\BOOTX64.EFI)..BO");
  assertEquals(efiFile(m.entries[2].path), "\\EFI\\BOOT\\BOOTX64.EFI");
  assertEquals(parseEfibootmgr("EFI variables are not supported on this system.").entries, []);
});

