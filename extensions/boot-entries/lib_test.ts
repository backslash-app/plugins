Deno.test("root scripts are quoted", () => {
  const grub = parseGrubCfg(GRUB_CFG).entries;
  assert(
    nextBootScript(grub[1]).endsWith(
      "grub-reboot 'gnulinux-advanced-5c0e8a7d>gnulinux-6.8.0-47-generic-advanced-5c0e8a7d'",
    ),
  );
  assert(nextBootScript(grub[5], "grub2-reboot").endsWith(`grub2-reboot 'Joe'\\''s "test" entry'`));
  const efi = parseEfibootmgr(EFI_18).entries[1];
  assert(nextBootScript(efi).includes("efibootmgr --bootnext 0000"));
  const sd = parseBootctl(BOOTCTL)![2];
  assert(nextBootScript(sd).endsWith("bootctl set-oneshot auto-windows"));
  assert(cancelNextScript("grub", "grub2-editenv").endsWith("grub2-editenv - unset next_entry"));
  assert(cancelNextScript("efi").includes("--delete-bootnext"));
  assert(cancelNextScript("systemd-boot").endsWith("bootctl set-oneshot ''"));
});

